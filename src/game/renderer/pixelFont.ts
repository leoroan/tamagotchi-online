export const GLYPH_WIDTH = 3;
export const GLYPH_HEIGHT = 5;

export function glyphFor(char: string): readonly string[] {
  return GLYPHS[char.toUpperCase()] ?? GLYPHS['?'] ?? ['###', '..#', '.#.', '...', '.#.'];
}

export function measureText(text: string, scale = 1, letterSpacing = 1): number {
  const count = text.length;
  if (count <= 0) return 0;
  return count * GLYPH_WIDTH * scale + (count - 1) * letterSpacing * scale;
}
